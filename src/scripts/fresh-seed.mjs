async function runFreshSeed() {
  console.log(`\n======================================================`);
  console.log(`🌱 SEEDING FRESH FIRESTORE & AUTH FOR: ${serviceAccount.project_id}`);
  console.log(`======================================================\n`);

  // Step A: Seed Authentication Users & Firestore User Profiles
  console.log('--- Step 1: Provisioning Demo Accounts ---');
  const userMap = {};

  for (const user of USERS_TO_SEED) {
    let authRecord;
    try {
      authRecord = await auth.createUser({
        email: user.email,
        password: user.password,
        displayName: user.displayName,
      });
      console.log(`✅ Created Auth User: ${user.email} (UID: ${authRecord.uid})`);
    } catch (err) {
      if (err.code === 'auth/email-already-exists') {
        authRecord = await auth.getUserByEmail(user.email);
        console.log(`ℹ️ Auth User Already Exists: ${user.email} (UID: ${authRecord.uid})`);
      } else {
        console.error(`❌ Failed creating Auth user ${user.email}:`, err.message);
        continue;
      }
    }

    userMap[user.role] = { uid: authRecord.uid, email: user.email, displayName: user.displayName };

    // Create Firestore User Doc
    // Note: NEVER store password in Firestore!
    await db.collection('users').doc(authRecord.uid).set({
      uid: authRecord.uid,
      email: user.email,
      displayName: user.displayName,
      role: user.role,
      segment: user.role === 'admin' ? 'VIP' : 'Regular',
      createdAt: new Date().toISOString(),
      wishlist: [],
    }, { merge: true });

    console.log(`✅ Synced Firestore Profile for: ${user.displayName} (Role: ${user.role})`);
  }

  // Step B: Seed Products
  console.log(`\n--- Step 2: Seeding Products (${PRODUCTS.length} items across 18 categories) ---`);
  const productsBatch = db.batch();
  const createdProductIds = [];

  for (const product of PRODUCTS) {
    const slug = product.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '')
      .substring(0, 45);
    const docId = `${slug}-${Math.random().toString(36).substring(2, 7)}`;
    const docRef = db.collection('products').doc(docId);

    const docData = {
      ...product,
      id: docId,
      currency: 'KES',
      createdAt: Timestamp.now(),
      updatedAt: Timestamp.now(),
      views: product.views || Math.floor(Math.random() * 500) + 120,
      cartCount: Math.floor(Math.random() * 40) + 5,
      ordersCount: Math.floor(Math.random() * 30) + 2,
      reviewsCount: product.reviewsCount || Math.floor(Math.random() * 20) + 1,
      averageRating: Number(product.averageRating.toFixed(1)),
      vendor: product.brand + ' Official Store',
      color: product.specs.color || 'Standard',
    };

    productsBatch.set(docRef, docData);
    createdProductIds.push({ id: docId, name: product.name, price: product.price, imageUrl: product.imageUrl });
  }

  await productsBatch.commit();
  console.log(`✨ Successfully seeded ${createdProductIds.length} products to Firestore!`);

  // Step C: Seed Product Reviews (Subcollections)
  console.log('\n--- Step 3: Seeding Sample Product Reviews ---');
  const reviewReviewers = [
    { name: 'David Mwangi', rating: 5, text: 'Fantastic performance! Arrived same-day in Nairobi in pristine condition.' },
    { name: 'Sarah Ochieng', rating: 5, text: 'Exceeded my expectations. Build quality and speeds are top notch.' },
    { name: 'Brian Kiprop', rating: 4, text: 'Very solid purchase, packaging was great and works smoothly with my setup.' },
  ];

  for (let i = 0; i < Math.min(6, createdProductIds.length); i++) {
    const prod = createdProductIds[i];
    const reviewer = reviewReviewers[i % reviewReviewers.length];
    const reviewId = `rev-${Math.random().toString(36).substring(2, 9)}`;

    await db.collection('products').doc(prod.id).collection('reviews').doc(reviewId).set({
      id: reviewId,
      userId: userMap['client']?.uid || 'client-demo-uid',
      userName: reviewer.name,
      rating: reviewer.rating,
      text: reviewer.text,
      timestamp: new Date().toISOString(),
    });
  }
  console.log('✅ Added verified reviews to top products.');

  // Step D: Seed Active Cart Items under Client User
  console.log('\n--- Step 4: Seeding Sample Cart for Client ---');
  if (userMap['client']) {
    const sampleItems = createdProductIds.slice(0, 2);
    for (const item of sampleItems) {
      await db.collection('users').doc(userMap['client'].uid).collection('cart').doc(item.id).set({
        productId: item.id,
        quantity: 1,
        name: item.name,
        price: item.price,
        imageUrl: item.imageUrl,
      });
      console.log(`🛒 Added to Client Cart: ${item.name}`);
    }
  }

  // Step E: Seed Orders Collection
  console.log('\n--- Step 5: Seeding Orders Collection ---');
  const sampleOrders = [
    {
      id: 'ORD-2026-1001',
      productName: createdProductIds[0]?.name || 'Apple MacBook Air M2',
      status: 'Delivered',
      timestamp: new Date(Date.now() - 86400000 * 3).toISOString(),
      total: createdProductIds[0]?.price || 165000,
      user: 'client@demo.com',
    },
    {
      id: 'ORD-2026-1002',
      productName: createdProductIds[1]?.name || 'Dell UltraSharp 27″ 4K',
      status: 'Delivered',
      timestamp: new Date(Date.now() - 86400000 * 2).toISOString(),
      total: createdProductIds[1]?.price || 84000,
      user: 'client@demo.com',
    },
    {
      id: 'ORD-2026-1003',
      productName: createdProductIds[4]?.name || 'Logitech MX Master 3S',
      status: 'Processing',
      timestamp: new Date(Date.now() - 3600000 * 5).toISOString(),
      total: createdProductIds[4]?.price || 15500,
      user: 'client@demo.com',
    },
    {
      id: 'ORD-2026-1004',
      productName: createdProductIds[5]?.name || 'Sony WH-1000XM5',
      status: 'Processing',
      timestamp: new Date(Date.now() - 3600000 * 2).toISOString(),
      total: createdProductIds[5]?.price || 46000,
      user: 'devmahnx@gmail.com',
    },
  ];

  for (const ord of sampleOrders) {
    await db.collection('orders').doc(ord.id).set(ord);
    console.log(`📦 Created Order: ${ord.id} - ${ord.productName} (KES ${ord.total.toLocaleString()})`);
  }

  // Step F: Seed Notifications (Admin alerts)
  console.log('\n--- Step 6: Seeding Admin Notifications ---');
  const sampleNotifications = [
    {
      title: 'New High-Value Order',
      message: 'Order ORD-2026-1001 placed by client@demo.com for KES 165,000.',
      type: 'order',
      read: false,
      createdAt: new Date().toISOString(),
    },
    {
      title: 'Stock Alert',
      message: 'ASUS ROG Strix RTX 4090 stock is running low (5 remaining).',
      type: 'inventory',
      read: false,
      createdAt: new Date().toISOString(),
    },
    {
      title: 'Store Initialization',
      message: 'TechStore Kenya catalog initialized with 70+ products.',
      type: 'system',
      read: true,
      createdAt: new Date().toISOString(),
    },
  ];

  for (const notif of sampleNotifications) {
    await db.collection('notifications').add(notif);
  }
  console.log('✅ Admin notifications created.');

  console.log('\n======================================================');
  console.log('🎉 SEEDING COMPLETED SUCCESSFULLY WITH ZERO ERRORS!');
  console.log('======================================================\n');
}

runFreshSeed().catch(err => {
  console.error('\n❌ Fatal Seeding Error:', err);
  process.exit(1);
});

